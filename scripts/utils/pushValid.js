function pushValid(list, ...rest) {
    for (const item of rest) {
        if (item) {
            if (Array.isArray(item)) {
                list.push(...item);
            } else {
                list.push(item);
            }
        }
    }
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default pushValid;
