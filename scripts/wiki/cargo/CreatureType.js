import parseEntries from './helpers/parseEntries.js';

// =====================================================================================================================
//  D E C L A R A T I O N S
// =====================================================================================================================
const ENTRIES = {
    construct: true,
    demon: true,
    dragon: true,
    embodiment: true,
    living: true,
    magic_creature: true,
    undead: true,
};

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
function CreatureType() {
    return parseEntries(ENTRIES, {
        domain: 'CreatureType',
        type: 'creature_type',
        prefix: 'base_class_',
        name_suffix: '',
    });
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default CreatureType;
