import parseEntries from './helpers/parseEntries.js';

// =====================================================================================================================
//  D E C L A R A T I O N S
// =====================================================================================================================
const ENTRIES = {
    fly: 'flyer',
    teleport: 'blink',
};

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
function Movement() {
    return parseEntries(ENTRIES, {
        domain: 'Movement',
        type: 'movement',
        prefix: 'base_passive_',
    });
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default Movement;
