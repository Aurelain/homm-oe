function buildLeftovers(parsed) {
    const lines = [];
    for (const key in parsed.sections) {
        lines.push('');
        lines.push(`==${key}==`);
        lines.push(parsed.sections[key]);
    }
    return lines;
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default buildLeftovers;
