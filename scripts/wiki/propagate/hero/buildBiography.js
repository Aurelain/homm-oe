import joinLines from '../../../utils/joinLines.js';

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
function buildBiography(info) {
    const {lang, id} = info;
    const lines = [];

    lines.push(`{{Biography|lang=${lang}|id=${id}}}`);

    return joinLines(lines);
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default buildBiography;
