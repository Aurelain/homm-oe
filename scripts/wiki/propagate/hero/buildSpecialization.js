import joinLines from '../../../utils/joinLines.js';

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================

/**
 *
 */
function buildSpecialization(info) {
    const {lang, id} = info;
    const lines = [];

    lines.push(`{{Specialization|lang=${lang}|id=${id}}}`);

    return joinLines(lines);
}

// =====================================================================================================================
//  E X P O R T
// =====================================================================================================================
export default buildSpecialization;
