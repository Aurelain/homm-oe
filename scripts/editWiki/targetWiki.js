import fs from 'fs';
import process from 'node:process';
import assume from '../utils/assume.js';

// =====================================================================================================================
//  D E C L A R A T I O N S
// =====================================================================================================================
const TARGET_JS_PATH = import.meta.dirname + '/TARGET.js';

// =====================================================================================================================
//  P U B L I C
// =====================================================================================================================
/**
 *
 */
const target = () => {
    let argument = process.argv.at(-1);
    assume(argument, 'Nothing to target!');
    assume(fs.existsSync(argument), `Cannot find file "${argument}"!`);

    const content = `export const TARGET = '${argument}';\n`;
    fs.writeFileSync(TARGET_JS_PATH, content);

    console.log(`OK, targeting "${argument.match(/[^\\\/]*$/)[0]}".`);
};

// =====================================================================================================================
//  R U N
// =====================================================================================================================
target();
